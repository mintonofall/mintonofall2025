export interface CompatLayer {
    title: string;
    tag: string;
    score: number;
    description: string;
}

export interface StyleAxisResult {
    score: number;
    summary: string;
    layers: CompatLayer[];
}

type PairEntry = [string, string, number, string]; // letterA, letterB, score, 설명

function pairKey(a: string, b: string): string {
    return [a, b].sort().join("");
}

function buildTable(entries: PairEntry[]): Map<string, { score: number; note: string }> {
    const map = new Map<string, { score: number; note: string }>();
    for (const [a, b, score, note] of entries) {
        map.set(pairKey(a, b), { score, note });
    }
    return map;
}


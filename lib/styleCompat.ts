function optionTag(question: StyleQuestion, letter: string): string {
    return question.options.find((o) => o.letter === letter)?.tag ?? letter;
}

function axisCompatibility(
    myAnswers: string[],
    partnerAnswers: string[],
    questions: StyleQuestion[],
    tables: Map<string, { score: number; note: string }>[],
): StyleAxisResult {
    const layers: CompatLayer[] = questions.map((q, i) => {
        const my = myAnswers[i];
        const partner = partnerAnswers[i];
        const entry = tables[i].get(pairKey(my, partner));
        const score = entry?.score ?? 75;
        const description = entry?.note ?? "무난하게 잘 어울리는 조합이에요.";

        return {
            title: q.title,
            tag: `${optionTag(q, my)} x ${optionTag(q, partner)}`,
            score,
            description,
        };
    });

    const score = Math.round(layers.reduce((sum, l) => sum + l.score, 0) / layers.length);
    const summary =
        score >= 85
            ? "손발이 척척 맞는 조합이에요."
            : score >= 70
              ? "무난하게 잘 어울리는 조합이에요."
              : "스타일 차이는 있지만 맞춰가면 좋아질 조합이에요.";

    return { score, summary, layers };
}

/** 4번 축: 소통·멘탈 궁합 (콜 습관, 실수 후 반응, 듀스 접전, 파트너 실수 대처, 패배 직후) */
export function commCompatibility(myAnswers: string[], partnerAnswers: string[]): StyleAxisResult {
    return axisCompatibility(myAnswers, partnerAnswers, COMM_QUESTIONS, COMM_TABLES);
}

/** 5번 축: 플레이 스타일 궁합 (포지션, 랠리 운영, 체력 배분, 템포, 위기 샷) */
export function playCompatibility(myAnswers: string[], partnerAnswers: string[]): StyleAxisResult {
    return axisCompatibility(myAnswers, partnerAnswers, PLAY_QUESTIONS, PLAY_TABLES);
}
